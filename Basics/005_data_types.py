# Python Data Types
#
# | Category | Full Name       | Short Form | Example             |
# |          |                 |            |                     |
# | Numeric  | Integer         | int        | 18                  |
# | Numeric  | Floating Point  | float      | 99.5                |
# | Text     | String          | str        | "Shadman"           |
# | Boolean  | Boolean         | bool       | True                |
# | Sequence | List            | list       | [1, 2, 3]           |
# | Sequence | Tuple           | tuple      | (1, 2, 3)           |
# | Set      | Set             | set        | {1, 2, 3}           |
# | Mapping  | Dictionary      | dict       | {"name": "Shakib"}  |
# | None     | None Type       | NoneType   | None                |

# Integer
age = 17
print(age)
print(type(age))


# Float
gpa = 5.00
print(gpa)
print(type(gpa))


# String
name = "Shakib"
print(name)
print(type(name))


# Boolean
is_student = True
print(is_student)
print(type(is_student))


# List
fruits = ["Apple", "Banana", "Mango"]
print(fruits)
print(type(fruits))


# Tuple
numbers = (1, 2, 3)
print(numbers)
print(type(numbers))


# Set
colors = {"Red", "Green", "Blue"}
print(colors)
print(type(colors))


# Dictionary
student = {"name": "Shakib"}
print(student)
print(type(student))


# NoneType
result = None
print(result)
print(type(result))
