# Assignment Operators
#
# | Operator | Full Name              | Example  |
# |          |                        |          |
# | =        | Assignment             | x = 10   |
# | +=       | Add and Assign         | x += 5   |
# | -=       | Subtract and Assign    | x -= 5   |
# | *=       | Multiply and Assign    | x *= 5   |
# | /=       | Divide and Assign      | x /= 5   |
# | %=       | Modulus and Assign     | x %= 5   |
# | **=      | Exponent and Assign    | x **= 5  |
# | //=      | Floor Division Assign  | x //= 5  |


# Assignment (=)
x = 10
print("Assignment:", x)


# Add and Assign (+=)
x = 10
x += 5
print("Add and Assign:", x)


# Subtract and Assign (-=)
x = 10
x -= 5
print("Subtract and Assign:", x)


# Multiply and Assign (*=)
x = 10
x *= 5
print("Multiply and Assign:", x)


# Divide and Assign (/=)
x = 10
x /= 5
print("Divide and Assign:", x)


# Modulus and Assign (%=)
x = 10
x %= 3
print("Modulus and Assign:", x)


# Exponent and Assign (**=)
x = 2
x **= 3
print("Exponent and Assign:", x)


# Floor Division Assign (//=)
x = 10
x //= 3
print("Floor Division Assign:", x)