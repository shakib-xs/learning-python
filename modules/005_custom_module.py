# Python Custom Module
#
# A custom module is a Python file created by the programmer.
#
# Syntax:
# import module_name
# module_name.function_name()


# Example:
# Suppose another file named calculator.py contains:
#
# def add(a, b):
#     return a + b
#
# Then we can import it like this:
#
# import calculator
# print(calculator.add(10, 20))


