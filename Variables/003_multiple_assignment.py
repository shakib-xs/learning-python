# Multiple Assignment:
# Assign values to multiple variables in a single line.


# 1. Assign different values to multiple variables
name, age, country = "Oriyo", 3, "Bangladesh"

print(name)
print(age)
print(country)
   

# 2. Assign multiple numbers
x, y, z = 10, 20, 30

print(x)
print(y)
print(z)


# 3. Assign the same value to multiple variables
a = b = c = 100

print(a)
print(b)
print(c)


# 4. Multiple assignment with different data types
text, number, is_valid = "Python", 10, True

print(text)
print(number)
print(is_valid)


# 5. Multiple assignment using existing variables
first = "Hello"
second = "World"

message = first + " " + second

print(message)
