# Python If-Else Statement

# Syntax:
# if condition:
#     statement
# else:
#     statement


number = 10
if number > 20:
    print("Number is greater than 20")
else:
    print("Number is not greater than 20")



number = 15
if number % 2 == 0:
    print("Even number")
else:
    print("Odd number")



age = int(input("Enter your age: "))
if age > 18:
    print("You are an adult person.")
else:
    print("You are not an adult person.")