# Python If-Elif-Else Statement

# Syntax:
# if condition:
#     statement
# elif condition:
#     statement
# else:
#     statement

marks = 75
if marks >= 80:
    print("Grade A")
elif marks >= 70:
    print("Grade B")
elif marks >= 60:
    print("Grade C")
elif marks >= 50:
    print("Grade D")
elif marks >= 40:
    print("Grade E")
else:
    print("Grade F")